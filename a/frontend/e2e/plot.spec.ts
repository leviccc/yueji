import { expect, test } from '@playwright/test'

test('recap, flashback, source jump and progress rollback', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.locator('.book-sidebar .el-select').click()
  await page.getByRole('option', { name: '长安来信 · A' }).click()
  await expect(page.getByText('已读至第 5 章')).toBeVisible()
  await page.getByRole('button', { name: '生成前情回顾' }).click()
  await expect(page.locator('.summary-prose')).toContainText('七年前')
  await expect(page.locator('.questions-section')).toContainText('匿名信是谁寄的')
  await page.screenshot({ path: '../output/desktop-recap.png', fullPage: true })
  await page.getByRole('spinbutton').fill('8')
  await page.getByRole('button', { name: '更新进度' }).click()
  await expect(page.getByText('已读至第 8 章')).toBeVisible()
  await page.getByRole('button', { name: '生成前情回顾' }).click()
  await expect(page.locator('.summary-prose')).toContainText('寄信人的身份已经确认，是顾伯')
  await page.getByRole('spinbutton').fill('5')
  await page.getByRole('button', { name: '更新进度' }).click()
  await expect(page.getByText('已读至第 5 章')).toBeVisible()
  await expect(page.locator('.summary-prose')).toHaveCount(0)
  await page.getByRole('tab', { name: '故事时间线', exact: true }).click()
  await expect(page.getByText('七年前交付旧信', { exact: true })).toBeVisible()
  await expect(page.getByText('待核对的时间线索')).toBeVisible()
  await expect(page.locator('.graph-edges > path').first()).toHaveAttribute('d', /^M /)
  await page.screenshot({ path: '../output/desktop-timeline.png', fullPage: true })
  await page.locator('.story-graph .evidence-links button').first().click()
  await expect(page.locator('.source-reader mark')).toBeVisible()
  await expect(page.locator('.source-reader mark')).not.toBeEmpty()
  await page.locator('.el-drawer__close-btn').click()
  await page.getByRole('tab', { name: '章节摘要', exact: true }).click()
  await expect(page.locator('.summary-prose')).toContainText('林晚交还旧信')
  await page.getByRole('tab', { name: '人物剧情线', exact: true }).click()
  await page.locator('.panel-toolbar .el-select').click()
  await page.getByRole('option', { name: '林晚', exact: true }).click()
  await expect(page.locator('.event-card.muted').first()).toBeVisible()
  expect(errors).toEqual([])
})

for (const width of [320, 375, 414, 768]) {
  test(`layout and evidence drawer at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/')
    await page.getByRole('tab', { name: '故事时间线', exact: true }).click()
    await expect(page.getByText('七年前交付旧信', { exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
    await page.locator('.story-graph .evidence-links button').first().click()
    await expect(page.locator('.source-reader mark')).toBeVisible()
    expect(await page.locator('.el-drawer').evaluate(element => element.getBoundingClientRect().width <= window.innerWidth)).toBeTruthy()
    await page.locator('.el-drawer__close-btn').click()
    await expect(page.locator('.el-drawer')).not.toBeVisible()
    if (width === 375) await page.screenshot({ path: '../output/mobile-timeline.png', fullPage: true })
  })
}
